export const LESSONS_PER_COURSE = 8;
export const TOTAL_LESSONS = COURSES.length * LESSONS_PER_COURSE; // 24

// globalIndex: 0..23 (сколько занятий пилот уже прошёл — используется и как индекс следующего)
export function getCourseIndex(globalIndex) {
  return Math.min(Math.floor(globalIndex / LESSONS_PER_COURSE), COURSES.length - 1);
}
export function getLessonIndexInCourse(globalIndex) {
  return globalIndex % LESSONS_PER_COURSE;
}
// Возвращает описание текущего/следующего занятия для пилота с прогрессом lessonsCompleted
export function getCurrentLessonInfo(lessonsCompleted) {
  const clamped = Math.min(lessonsCompleted, TOTAL_LESSONS - 1);
  const courseIndex = getCourseIndex(clamped);
  const lessonIndexInCourse = getLessonIndexInCourse(clamped);
  const course = COURSES[courseIndex];
  return { course, courseIndex, lessonIndexInCourse, lesson: course.lessons[lessonIndexInCourse] };
}
// Курс и позиция внутри курса для конкретного пройденного занятия (для истории тренировок)
export function getCourseAndLessonForGlobalIndex(globalIndex) {
  const courseIndex = getCourseIndex(globalIndex);
  const lessonIndexInCourse = getLessonIndexInCourse(globalIndex);
  return { course: COURSES[courseIndex], courseIndex, lessonIndexInCourse };
}

